import { existsSync, readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
const root=process.cwd();
const read=(f)=>readFileSync(resolve(root,f),"utf8");
const exists=(f)=>existsSync(resolve(root,f));
const pkg=JSON.parse(read("package.json"));
const checks=[]; const expect=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const migrations=readdirSync(resolve(root,"supabase/migrations")).filter(x=>x.endsWith(".sql"));
expect("package and lock release agree",pkg.version===JSON.parse(read("package-lock.json")).version && /^1\.0\.0-rc\.\d+$/.test(pkg.version));
expect("feature freeze retained",exists("FEATURE_FREEZE_RC18.md"));
expect("RC19 QA retained",exists("FULL_QA_SECURITY_PERFORMANCE_RC19.md"));
expect("RC20 setup guide",exists("SETUP_WINDOWS_RC20.md"));
expect("RC20 final checklist",exists("FINAL_PILOT_CHECKLIST_RC20.md"));
expect("Windows one-click setup",exists("scripts/setup-windows.ps1"));
expect("23+ migrations packaged",migrations.length>=23);
expect("Operations Center route",exists("src/app/operations/page.tsx"));
expect("Ops Health route",exists("src/app/ops-health/page.tsx"));
expect("Pilot Check route",exists("src/app/pilot-check/page.tsx"));
expect("Release Check route",exists("src/app/release-check/page.tsx"));
expect("Health API",exists("src/app/api/health/route.ts"));
expect("Maps Geocode API",exists("src/app/api/maps/geocode/route.ts"));
expect("Maps Routes API",exists("src/app/api/maps/route/route.ts"));
expect("AYA API",exists("src/app/api/ai-assistant/route.ts"));
expect("verify:env script wired",pkg.scripts?.["verify:env"]?.includes("verify-env.mjs"));
expect("verify:runtime script wired",pkg.scripts?.["verify:runtime"]?.includes("verify-runtime.mjs"));
expect("verify chain includes pilot candidate",pkg.scripts?.verify?.includes("verify:pilot"));
expect("final verification command wired",pkg.scripts?.["verify:final"]==="npm run verify:env && npm run verify");
for(const item of checks) console.log(`${item.ok?"PASS":"FAIL"} · ${item.name}`);
const failed=checks.filter(x=>!x.ok);
if(failed.length){console.error(`Pilot candidate verification failed: ${failed.length}/${checks.length}`);process.exit(1);}
console.log(`Pilot candidate verification PASS (${checks.length}/${checks.length})`);
