import assert from 'node:assert/strict';
import * as THREE from 'three';
import {applyMeshDisplay,layerState,isContextClick} from '../src/lib/cad-display';
const settings={show_scan:true,show_design:true,opacity:1,show_upper:true,show_lower:true,upper_opacity:.4,lower_opacity:.8};
assert.deepEqual(layerState(settings,'upper'),{visible:true,opacity:.4});
assert.equal(layerState({...settings,show_upper:false},'upper').visible,false);
assert.equal(layerState({...settings,show_upper:false},'lower').visible,true);
assert.equal(layerState({...settings,show_scan:false},'upper').visible,false);
assert.equal(layerState({...settings,opacity:0},'design').visible,false);
assert.equal(layerState({...settings,opacity:99},'design').opacity,1);
const mesh=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshStandardMaterial());
const original=new Float32Array(mesh.geometry.getAttribute('position').array);
applyMeshDisplay(mesh,{visible:true,opacity:.25});assert.equal(mesh.material.opacity,.25);assert.equal(mesh.material.depthWrite,false);
applyMeshDisplay(mesh,{visible:false,opacity:1});assert.equal(mesh.visible,false);assert.equal(mesh.material.transparent,false);
assert.deepEqual(new Float32Array(mesh.geometry.getAttribute('position').array),original);
const upper=new THREE.BoxGeometry();upper.translate(100,0,20);const lower=new THREE.BoxGeometry();lower.translate(100,0,-20);
const center=new THREE.Vector3();upper.computeBoundingBox();upper.boundingBox!.getCenter(center);
upper.translate(-center.x,-center.y,-center.z);lower.translate(-center.x,-center.y,-center.z);lower.computeBoundingBox();
assert.equal(lower.boundingBox!.getCenter(new THREE.Vector3()).z,-40);
assert.equal(isContextClick({x:10,y:10,pointer:1},{x:12,y:12,pointer:1}),true);
assert.equal(isContextClick({x:10,y:10,pointer:1},{x:30,y:10,pointer:1}),false);
assert.equal(isContextClick({x:10,y:10,pointer:1},{x:10,y:10,pointer:2}),false);
console.log('PASS: per-layer visibility, opacity bounds/depth, geometry unchanged, shared jaw coordinates, context click threshold.');
